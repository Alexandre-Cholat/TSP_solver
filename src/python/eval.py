def visualize_multiple_instances_with_scaling(
    n_nodes_list: list[int] | None = None,
    n_instances: int = 5,
):
    """
    Benchmarks average runtime across increasing instance dimensions (N) for
    AntSwarm vs Held-Karp without terminal prints, saving the plot to visualisations/.
    """
    if n_nodes_list is None:
        n_nodes_list = [5, 10, 15, 20]

    solvers = {
        "AntSwarm": tsp_bindings.AntSwarmSolver(),
        "HeldKarp": tsp_bindings.HeldKarpSolver(),
    }

    avg_times_ms = {name: [] for name in solvers}

    for n_nodes in n_nodes_list:
        instances = generate_n_random_matrix(n_nodes, n_instances)
        matrices = [matrix for matrix, _ in instances]

        for name, solver in solvers.items():
            total_elapsed, _, _ = measure_solver_multiple(solver, matrices)
            avg_elapsed_ms = (total_elapsed / n_instances) * 1000.0
            avg_times_ms[name].append(avg_elapsed_ms)

    fig, ax = plt.subplots(figsize=(8, 5))
    colors = {"AntSwarm": "#1f77b4", "HeldKarp": "#d62728"}

    for name, times in avg_times_ms.items():
        ax.plot(
            n_nodes_list,
            times,
            marker="o",
            linewidth=2,
            color=colors.get(name),
            label=name,
        )

    ax.set_yscale("log")
    ax.set_xticks(n_nodes_list)
    ax.set_title(f"Runtime Scaling Comparison: AntSwarm vs Held-Karp (Instances per N = {n_instances})")
    ax.set_xlabel("Instance Dimension (N Nodes)")
    ax.set_ylabel("Average Execution Time (ms, log scale)")
    ax.grid(True, which="both", linestyle="--", alpha=0.4)
    ax.legend()
    plt.tight_layout()

    vis_dir = PROJECT_ROOT / "visualisations"
    vis_dir.mkdir(parents=True, exist_ok=True)
    output_file = vis_dir / "runtime_scaling.png"
    plt.savefig(output_file, dpi=150)
    plt.show()

